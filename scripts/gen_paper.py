heading("3.2 检测层：受控平等融合的双判据检测", level=2)
body(
    "检测层由两条误差互不相关的判据构成。第一条判据是EfficientAD [2]的师生—教师"
    "蒸馏网络：教师网络在大规模自然图像上预训练并冻结，学生网络仅在迁移阶段的"
    "正常样本上训练，学习模仿教师在正常区域的特征输出；由于学生从未见过异常样本，"
    "其与教师输出的差异在异常区域会显著增大，构成检测信号。本文进一步引入两个"
    "不同随机种子的学生网络构成集成，教师网络在两个学生之间共享，不产生额外的"
    "教师前向开销。第二条判据是DINOv2 [3]自监督视觉特征构成的图级协同检测器："
    "对迁移阶段的正常样本与缺陷样本分别提取特征并做同样的分数标准化，与EfficientAD"
    "分支的标准化分数取逐图最大值作为最终判据（即两条判据平等竞争，只要任意一条"
    "判定为异常即采信）。"
)
body(
    "该设计的动机来自一个明确的失效现象：EfficientAD单独判定图级异常时，在特定"
    "品类上会出现系统性漏判——不是随机误差，而是该品类的异常特征分布与正常特征"
    "分布在教师—学生残差空间中重叠，导致几乎全部异常样本的分数落入正常区间。"
    "由于两条判据基于完全不同的特征空间（卷积残差 vs. 自监督语义特征），"
    "二者出现同向系统性偏差的概率较低。实测中，若因延时预算限制而临时移除DINO"
    "协同判据，该品类的图级判定准确率由0.811骤降至0.171，证实这是一处不可裁剪"
    "的组件（第4.5节的延时自适应策略据此将其排除在可裁剪清单之外）。"
)
body(
    "在检测层判定“正常”但分数处于自适应灰区（超过阈值的固定比例但未达阈值）"
    "且定位层信号超过独立标定的门限时，系统提供一次受控的“翻正”补检：该门限"
    "与灰区比例均在迁移阶段的内部数据上按“零误翻”条件标定——即该补检机制在"
    "标定数据上不产生任何新增误报，标定失败则整体禁用。此设计只增加召回、不改变"
    "原有判定边界，因此不改变检测层其余部分已验证的行为。"
)

