footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
add_field(footer_p, "PAGE")


def set_ea(run, font):
    """给 run 设置东亚字体(w:eastAsia),否则中文在部分Word版本下会退回西文字体。"""
    run.element.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), font)


